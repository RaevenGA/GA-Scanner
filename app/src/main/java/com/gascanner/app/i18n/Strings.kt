val LocalStrings = staticCompositionLocalOf { Strings() }

object Languages {
    val names = linkedMapOf(
        "en" to "English",
        "pl" to "Polski",
        "de" to "Deutsch",
        "fr" to "Français",
        "es" to "Español",
    )

    fun resolve(code: String): String =
        if (code == "system" || code !in names) Locale.getDefault().language.takeIf { it in names } ?: "en" else code

    fun strings(code: String): Strings = when (resolve(code)) {
        "pl" -> StringsPl
        "de" -> StringsDe
        "fr" -> StringsFr
        "es" -> StringsEs
        else -> Strings()
    }
}
